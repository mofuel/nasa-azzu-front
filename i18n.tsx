const phrases = Object.keys(english).filter(key => key.length > 1 && english[key] !== key).sort((a, b) => b.length - a.length)
const escaped = phrases.map(key => key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
const phrasePattern = new RegExp(escaped.join('|'), 'g')

export function translate(text: string, language: Language): string {
  if (language === 'es') return text
  return (english[text] ?? text.replace(phrasePattern, phrase => english[phrase]))
    .replace(/(\d),(\d)/g, '$1.$2')
    .replace(/(ranges from [-+\d.]+\s*[°mK]?) a /g, '$1 to ')
}

export const formatNumber = (value: number, language: Language, digits = 2) =>
  value.toLocaleString(language === 'en' ? 'en-US' : 'es', {maximumFractionDigits: digits})

const LanguageContext = createContext<{
  language: Language; setLanguage: (language: Language) => void; t: Translator; number: (value: number) => string
} | null>(null)

export function LanguageProvider({children}: {children: ReactNode}) {
  const [language, updateLanguage] = useState<Language>(() => {
    try { return localStorage.getItem('azzu-language') === 'es' ? 'es' : 'en' } catch { return 'en' }
  })
  useEffect(() => { document.documentElement.lang = language }, [language])
  const value = useMemo(() => ({
    language,
    setLanguage(next: Language) {
      updateLanguage(next)
      try { localStorage.setItem('azzu-language', next) } catch { /* The switch also works without storage. */ }
    },
    t: (text: string) => translate(text, language),
    number: (value: number) => formatNumber(value, language),
  }), [language])
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const value = useContext(LanguageContext)
  if (!value) throw new Error('LanguageProvider is missing')
  return value
}
